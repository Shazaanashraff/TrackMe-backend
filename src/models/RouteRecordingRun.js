const mongoose = require('mongoose');

// One recording ride of a custom route: the raw GPS track a driver produced between
// pressing GO and ending the journey while the route was in RECORDING, plus its
// map-matched road geometry. The raw track is kept so a ride can be re-matched
// later (a better matcher, a self-hosted one) without re-driving.
const MAX_POINTS = 5000;

const pointSchema = new mongoose.Schema({
  lat: { type: Number, required: true },
  lng: { type: Number, required: true },
  t: { type: Number, default: null },   // epoch ms
  acc: { type: Number, default: null }  // metres
}, { _id: false });

const stopSchema = new mongoose.Schema({
  lat: { type: Number, required: true },
  lng: { type: Number, required: true },
  t: { type: Number, default: null },
  name: { type: String, default: '', trim: true, maxlength: 80 }
}, { _id: false });

const routeRecordingRunSchema = new mongoose.Schema({
  routeId: { type: String, required: true, index: true, uppercase: true, trim: true },
  vehicleId: { type: mongoose.Schema.Types.ObjectId, ref: 'Vehicle', required: true },
  driverId: { type: mongoose.Schema.Types.ObjectId, ref: 'Driver', required: true },
  managerId: { type: mongoose.Schema.Types.ObjectId, ref: 'Manager', default: null },
  // Idempotency key generated by the driver app at GO, so a retried upload is one run.
  clientRunId: { type: String, required: true, trim: true },
  // 1..N, assigned when the run is accepted.
  runNumber: { type: Number, default: null },
  status: {
    type: String,
    enum: ['PENDING_MATCH', 'ACCEPTED', 'REJECTED', 'DISCARDED'],
    default: 'PENDING_MATCH'
  },
  // TOO_FEW_POINTS | TOO_SHORT | DUPLICATE | NOT_SAME_ROUTE
  rejectReason: { type: String, default: '' },
  startedAt: { type: Date, default: null },
  endedAt: { type: Date, default: null },
  durationSec: { type: Number, default: 0 },
  distanceM: { type: Number, default: 0 },
  points: {
    type: [pointSchema],
    default: [],
    validate: [(v) => v.length <= MAX_POINTS, `A ride holds at most ${MAX_POINTS} points`]
  },
  stops: { type: [stopSchema], default: [] },
  matched: {
    polyline: { type: String, default: '' },
    confidence: { type: Number, default: null },
    provider: { type: String, default: '' },
    matchedAt: { type: Date, default: null }
  }
}, { timestamps: true });

routeRecordingRunSchema.index({ routeId: 1, status: 1 });
routeRecordingRunSchema.index({ routeId: 1, clientRunId: 1 }, { unique: true });

routeRecordingRunSchema.statics.MAX_POINTS = MAX_POINTS;

module.exports = mongoose.model('RouteRecordingRun', routeRecordingRunSchema);
